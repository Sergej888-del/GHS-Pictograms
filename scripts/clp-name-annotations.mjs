/**
 * Разрез по разделителю синонимов ТОЛЬКО на нулевой глубине скобок.
 *
 * ⚠⚠ Прежний код резал на любой глубине, и замер дал 1 594 лишних куска у
 * 1 284 записей: у стекловолокна 014-046-00-4 «the process list does not
 * preclude innovation).]» уезжало отдельным «синонимом».
 *
 * ⚠ Если скобки в ячейке НЕ СХОДЯТСЯ, глубина навсегда остаётся ненулевой и
 * разрез пропал бы целиком — тогда режем наивно, как раньше. Это не ухудшает
 * сегодняшнее поведение, а `splitName` такие записи называет поимённо.
 *
 * ⚠⚠ `limit` — СКОЛЬКО РАЗ РЕЗАТЬ, а не сколько кусков вернуть. У составной
 * записи он равен `COMPOSITE_HEAD − 1`, и при нуле ячейка не режется вовсе.
 *
 * ⭐ Хвост после последнего разреза остаётся ДОСЛОВНЫМ куском исходной ячейки —
 * он НЕ собирается обратно из частей. Склейка потеряла бы, каким знаком
 * регламент разделил компоненты: греческая редакция ставит ано телиа «·», а не
 * «;», и «восстановленное» имя разошлось бы с напечатанным в Annex VI.
 */
export function splitTopLevel(text, limit = Infinity) {
  const s = String(text ?? '');
  const naive = () => {
    const out = [];
    let rest = s;
    while (out.length < limit) {
      const at = rest.search(/[;·]/);
      if (at < 0) break;
      out.push(rest.slice(0, at));
      rest = rest.slice(at + 1);
    }
    out.push(rest);
    return out.map((x) => x.trim()).filter(Boolean);
  };
  if (!bracketsBalanced(s)) return naive();
  const out = [];
  const stack = [];
  let buf = '';
  let cuts = 0;
  for (const ch of s) {
    if (OPEN[ch]) stack.push(ch);
    else if (CLOSE[ch]) { if (stack[stack.length - 1] === CLOSE[ch]) stack.pop(); }
    if (SEPARATORS.has(ch) && stack.length === 0 && cuts < limit) {
      out.push(buf); buf = ''; cuts++;
    } else buf += ch;
  }
  out.push(buf);
  return out.map((x) => x.trim()).filter(Boolean);
}

const LETTER = /\p{L}/u;
const MARKER_RE = /\[(\d{1,2})\]/g;

/**
 * Маркеры групповой записи `[1] [2] [3]`.
 *
 * ⚠⚠ ЦИФРА В СКОБКАХ БЫВАЕТ И ЧАСТЬЮ НОМЕНКЛАТУРЫ: `spiro[[1]benzopyrano…`,
 * `benzofuro[3a,3,2-ef][2]benzazepin-6-one`. Прежний шаблон брал их за маркеры
 * и ОБРЕЗАЛ имя по ним — у 606-094-00-5 и 606-112-00-1 во ВСЕХ 23 языках в базу
 * уехал огрызок «…-1-phenyl-spiro[».
 *
 * ⭐ Отличие замерено, а не угадано: номенклатурная цифра вклеена с ОБЕИХ сторон
 * — слева `[`, `]` или дефис, справа буква. Настоящий маркер хотя бы с одной
 * стороны свободен, включая слипшиеся `salt[8]`, `p -Xylol[2];`, `(ISO)[1];`.
 * ⚠ Отбор проверен полностью: расхождений со старым правилом ровно 46, и все 46
 * — это те самые две записи × 23 языка.
 */
export function findMarkers(cell) {
  const s = String(cell ?? '');
  const out = [];
  MARKER_RE.lastIndex = 0;
  let m;
  while ((m = MARKER_RE.exec(s)) !== null) {
    const prev = m.index === 0 ? '' : s[m.index - 1];
    const next = s[m.index + m[0].length] ?? '';
    if ((prev === '[' || prev === ']' || prev === '-' || prev === '‐' || prev === '–') && LETTER.test(next)) continue;
    out.push({ n: Number(m[1]), index: m.index, length: m[0].length });
  }
  return out;
}

/**
 * Хвостовая сбалансированная группа `[…]`.
 *
 * ⚠⚠ ТРЕБОВАНИЕ ОТДЕЛЯЮЩЕГО ЗНАКА ПЕРЕД СКОБКОЙ — ЭТО И ЕСТЬ ЗАЩИТА
 * НОМЕНКЛАТУРЫ. `…bis[ N' -phenylurea]` и `tris[3-аминопропил-…]` — скобка
 * приклеена к слову, это часть химического имени. `piperazine [solid]` —
 * отделена. Без этой проверки под нож пошли бы 2 134 записи.
 */
function tailGroup(seg) {
  const s = String(seg ?? '');
  if (!s.endsWith(']')) return null;
  let depth = 0;
  for (let i = s.length - 1; i >= 0; i--) {
    if (s[i] === ']') depth++;
    else if (s[i] === '[') {
      depth--;
      if (depth === 0) {
        const before = s.slice(0, i);
        if (i !== 0 && !TRAILING.test(before)) return null;
        return { inner: s.slice(i + 1, -1).trim(), before: before.replace(TRAILING, '') };
      }
    }
  }
  return null;
}

/**
 * Снять с куска имени хвостовые скобочные примечания.
 * ⚠ Имя НЕ переписывается: возвращается только то, что осталось, и список снятого.
 */
function peel(chunk, indexNumber, sink) {
  let name = String(chunk ?? '').trim();
  // ⚠ Цикл, а не одна проверка: у 607-721-00-5 их две подряд — `[MBM]` и
  // `[formaldehyde released from N,N′-methylenebismorpholine]`.
  for (;;) {
    const g = tailGroup(name);
    if (!g) break;
    const kind = classifyAnnotation(indexNumber, g.inner);
    if (kind === 'name') break;   // скобка — часть имени
    if (!g.before) break;         // скобка и есть всё имя, снимать нечего
    sink.push({ kind, text: g.inner });
    name = g.before;
  }
  // ⚠ `silver massive:` — двоеточие оставалось висеть после снятия примечания.
  return name.replace(TRAILING, '').trim();
}

/**
 * Разбор ячейки имени на формы и примечания.
 *
 * 1. ЕСТЬ МАРКЕРЫ — ГРУППОВАЯ запись: под одним индексным номером идут разные
 *    вещества, номер маркера привязывает имя к своей позиции в колонках EC и
 *    CAS. Формы делятся ПО МАРКЕРАМ, а не по точке с запятой.
 * 2. МАРКЕРОВ НЕТ — ОДНО вещество, точки с запятой разделяют СИНОНИМЫ.
 *    ⚠⚠ Число синонимов между языками ЗАКОННО РАЗНОЕ: «Kohlenstoffmonoxid;
 *    Kohlenmonoxid; Kohlenoxid» против одного «carbon monoxide». Требовать
 *    совпадения — значит забраковать сотни верных записей.
 *
 * Возвращает, сверх прежнего: `annotations` — снятое, по классам, и
 * `unbalanced` — признак того, что скобки в ячейке не сходятся.
 */
/**
 * ⚠⚠ ЧТО ДЕЛАТЬ С ХВОСТОМ ПОСЛЕ ПОСЛЕДНЕГО МАРКЕРА — ТАБЛИЦА ПО НОМЕРУ ЗАПИСИ.
 *
 * Замер по 3 556 групповым записям 23 языков: хвост непустой у 80, и это 19
 * индексных номеров. Два из них (617-010-01-9 и 617-010-00-1) снимаются
 * механически — там хвост целиком скобочное примечание. Остальные 17 здесь.
 *
 * ⚠⚠ ПО ВИДУ ТЕКСТА ЭТИ СЛУЧАИ НЕРАЗЛИЧИМЫ. «and its salts» и
 * «tri-méthylamine à …%» — обе строки просто текст после «[2]». Первую печатать
 * на этикетке нельзя (это не имя), вторую нельзя терять (это третий член).
 *
 * ⭐ РАЗЛИЧАЕТ ИХ НЕ ТЕКСТ, А ЧИСЛО ЧЛЕНОВ У ОСТАЛЬНЫХ 22 ЯЗЫКОВ. Свидетельство
 * выписано в комментарии к каждой строке: «{2:1, 3:22}» значит, что у 22 языков
 * запись состоит из трёх членов, а у одного — из двух, и хвост у этого одного
 * есть ровно тот член, которому источник забыл поставить маркер.
 *
 * ⚠ Таблица закреплена ЗА ИНДЕКСНЫМ НОМЕРОМ и одинакова во всех языках — как и
 * таблица классов скобок. Срабатывает она только там, где хвост реально есть,
 * поэтому у 20 языков записи 613-089-00-1 правило просто не применяется.
 *
 *   member  — хвост это ЧЛЕН, которому источник не поставил маркер;
 *             становится следующим по счёту членом записи;
 *   append  — маркер стоит ВНУТРИ имени, хвост дописывается к последнему члену;
 *   scope   — оговорка об охвате записи, идёт в annotations и НЕ печатается;
 *   unclear — источник противоречив; хвост остаётся в поле `tail`, запись
 *             помечена, и предлагать её формы как надёжные нельзя.
 */
export const TAIL_CLASS = new Map([
  /**
   * ⚠⚠ ДВЕ ЗАПИСИ, ГДЕ ОГОВОРКА ВПЛЕТЕНА МЕЖДУ МАРКЕРАМИ, А НЕ ТОЛЬКО В ХВОСТЕ.
   *
   * 607-718-00-9 {3:23} — «perfluorononan-1-oic acid [1] and its sodium [2] and
   * ammonium [3] salts». Членов действительно три, но ИМЁН в ячейке нет: между
   * маркерами лежат куски предложения. Разрез по маркерам даёт формы
   * «and its sodium» и «and ammonium» — на этикетке это выглядит как название и
   * названием не является. ⚠⚠ Такой мусор опаснее видимого: «; Isobutan» человек
   * заметит и сотрёт, «and its sodium» — примет за имя.
   *
   * 607-434-00-5 {1:23} — «mecoprop-P (ISO) [1] and its salts; ( R )-2-(…)
   * propionic acid [1] and its salts»: маркер [1] стоит дважды, между именами
   * снова оговорка. Склейка даёт «mecoprop-P (ISO); and its salts; ( R )-2-…».
   *
   * Снять оговорку изнутри можно только зная, что «and its salts», «e suoi
   * sali», «und ihre Salze» — не имена. Это словарь на 23 языка, то есть ровно
   * тот перевод, которого мы себе не позволяем. ⚠ Поэтому обе записи помечены:
   * формы у них не предлагаются как надёжные, а человеку показывается ячейка
   * регламента целиком.
   */
  ['607-718-00-9', 'unclear'],
  ['607-434-00-5', 'unclear'],
  // {0:22, 1:1} — у 22 языков маркеров НЕТ ВОВСЕ, маркер голландской версии
  // лишний. Хвост «en zijn zouten» = «и его соли».
  ['612-198-00-1', 'scope'],
  ['612-199-00-7', 'scope'],
  // {3:23} — три члена у всех, включая румынский. ⚠ Хвост «de disodiu» — это
  // ПОРЯДОК СЛОВ: «…disulfonat [3] de disodiu» = «динатрия …дисульфонат».
  // Маркер стоит внутри имени, а не после него.
  ['607-774-00-4', 'append'],

  // ── Источник забыл маркер: у языка с хвостом членов МЕНЬШЕ, чем у прочих ──
  ['613-089-00-1', 'member'],   // {2:3,  3:20}  FR, LT, SV
  ['607-700-00-0', 'member'],   // {1:2,  2:21}  DA, FR
  ['015-156-00-5', 'member'],   // {1:2,  2:21}  FR, NL
  ['607-044-00-5', 'member'],   // {1:1,  2:22}  CS
  ['609-021-00-5', 'member'],   // {1:1,  2:22}  CS
  ['613-043-00-0', 'member'],   // {1:1,  2:22}  FI
  ['607-129-00-7', 'member'],   // {1:1,  2:22}  FR
  ['616-227-00-9', 'member'],   // {1:1,  2:22}  FR
  ['612-001-01-6', 'member'],   // {2:1,  3:22}  FR
  ['612-130-00-0', 'member'],   // {2:1,  3:22}  FR
  // {1:1, 2:22} HU. ⚠ Хвост кончается НЕЗАКРЫТЫМ маркером «[2» — опечатка
  // разметки венгерской версии; висящий огрызок снимается.
  ['607-125-00-5', 'member'],

  /**
   * ⚠⚠ {0:1, 3:22} — И ЭТО ЕДИНСТВЕННЫЙ СЛУЧАЙ, КОТОРЫЙ МЫ НЕ РЕШАЕМ.
   *
   * У аллетрина маркеры расставлены по-разному в разных языках: английская
   * версия пишет «… [1] S -bioallethrin; [3] ( S )-3-allyl-…; [2] esbiothrin;
   * … [3]» — то есть номер 3 стоит дважды, а 2 между ними; датская пишет
   * «[1] … ; [2] S -bioallethrin; [3] ( S )-3-allyl-…» и оставляет esbiothrin
   * вовсе без номера; итальянская не ставит ни одного маркера.
   *
   * Языки НЕ СОГЛАСНЫ между собой в том, какой член какой, — а именно согласие
   * языков и есть то основание, на котором стоят все остальные строки этой
   * таблицы. Дописать сюда своё прочтение значит решить за регламент, какое
   * вещество лежит в упаковке. Запись помечается, формы предлагаются как
   * ненадёжные, и человеку видно почему.
   */
  ['006-025-00-3', 'unclear'],
]);

/** Незакрытый маркер на конце хвоста: «…metakrilát [2». ⚠ Только на конце. */
const DANGLING_MARKER = /\s*\[\d{1,2}\s*$/;

export function splitName(cellRaw, indexNumber = '') {
  const cell = String(cellRaw ?? '').trim();
  const annotations = [];
  const unbalanced = !bracketsBalanced(cell);
  const marks = findMarkers(cell);

  if (marks.length) {
    const members = {};
    let pos = 0;
    for (const m of marks) {
      const chunk = trimSeparators(cell.slice(pos, m.index));
      if (chunk) {
        const name = peel(chunk, indexNumber, annotations);
        /**
         * ⚠⚠ ПОВТОРНЫЙ НОМЕР МАРКЕРА — НЕ ЗАТИРАНИЕ, А ВТОРОЕ ИМЯ ТОГО ЖЕ ЧЛЕНА.
         *
         * У 607-434-00-5 регламент пишет — одинаково во всех 23 языках:
         *   mecoprop-P (ISO) [1] and its salts; ( R )-2-(…)propionic acid [1] …
         * то есть «[1]» стоит дважды: сначала при общепринятом имени, потом при
         * систематическом. Присваивание затирало первое вторым, и в базе от
         * записи оставалось «and its salts; ( R )-2-(4-chloro-2-methylphenoxy)
         * propionic acid» — ИМЕНИ «mecoprop-P (ISO)» НЕ БЫЛО ВОВСЕ.
         *
         * ⚠ Замер: 46 записей теряли по члену. Склейка через «; » — тот же вид,
         * которым регламент разделяет синонимы внутри одного члена.
         */
        if (name) members[m.n] = members[m.n] ? `${members[m.n]}; ${name}` : name;
      }
      pos = m.index + m.length;
    }

    /**
     * ⚠⚠ ХВОСТ ПОСЛЕ ПОСЛЕДНЕГО МАРКЕРА ВЫБРАСЫВАЛСЯ МОЛЧА — А ОН НИКОГДА НЕ
     * ПУСТОЙ. Замер по 3 556 групповым записям 23 языков: непустой хвост у 80,
     * и это 19 разных индексных номеров.
     *
     * ⭐ Здесь снимается ровно тот случай, который решается без всякой таблицы:
     * хвост ЦЕЛИКОМ является скобочным примечанием и относится ко ВСЕЙ записи.
     *   617-010-01-9: «… cyclohexanone, peroxide [4] [≤ 91 % solution]»
     * ⚠⚠ Это ПРИМЕЧАНИЕ КЛАССА composition у 22 языков, то есть по Annex VI
     * Part 1 п. 1.1.1.4 — текст, ОБЯЗАННЫЙ печататься на этикетке. Он терялся.
     *
     * ⚠ Остальной хвост (текст, а не примечание) здесь НЕ разбирается: у одних
     * записей это общая оговорка «and its salts», у других — член, которому
     * источник забыл поставить маркер. Отличить их по виду текста нельзя, и
     * гадать на этикетке мы не будем — они возвращаются полем `tail`.
     */
    let tail = trimSeparators(cell.slice(pos));
    if (tail.endsWith(']')) {
      const g = tailGroup(tail);
      if (g && !g.before) {
        const kind = classifyAnnotation(indexNumber, g.inner);
        if (kind !== 'name') { annotations.push({ kind, text: g.inner }); tail = ''; }
      }
    }

    /**
     * ⚠⚠ ОСТАВШИЙСЯ ХВОСТ — ПО ТАБЛИЦЕ, А НЕ ПО ВИДУ ТЕКСТА. См. TAIL_CLASS.
     * ⚠ Номера, которого в таблице нет, здесь не бывает: 19 номеров с хвостом
     * перечислены целиком. Но если регламент однажды заведёт двадцатый, хвост
     * останется в `tail` и попадёт в отчёт, а не пропадёт молча.
     */
    const rule = TAIL_CLASS.get(indexNumber);
    if (tail && rule) {
      const nums = Object.keys(members).map(Number);
      const top = nums.length ? Math.max(...nums) : 0;
      if (rule === 'member') {
        const name = peel(tail.replace(DANGLING_MARKER, '').trim(), indexNumber, annotations);
        if (name) { members[top + 1] = name; tail = ''; }
      } else if (rule === 'append' && top) {
        members[top] = `${members[top]} ${tail}`.replace(/\s+/g, ' ').trim();
        tail = '';
      } else if (rule === 'scope') {
        annotations.push({ kind: 'scope', text: tail });
        tail = '';
      }
      else if (rule === 'unclear') {
        // ⚠ Хвост НЕ выбрасывается и НЕ выдаётся за имя: он ложится отдельным
        // классом, по которому панель узнаёт, что формам этой записи верить
        // нельзя, и показывает человеку ячейку регламента целиком.
        annotations.push({ kind: 'unclear', text: tail });
      }
    }

    const keys = Object.keys(members).map(Number).sort((a, b) => a - b);
    return {
      kind: 'group', members,
      forms: keys.map((k) => members[k]),
      synonyms: [], annotations, unbalanced,
      tail: tail || undefined,
      /** ⚠ Разбор ненадёжен: языки не согласны между собой. См. TAIL_CLASS. */
      unclear: rule === 'unclear' && Boolean(tail) ? true : undefined,
    };
  }

  /**
   * ⚠⚠ СОСТАВНАЯ ЗАПИСЬ РЕЖЕТСЯ НЕ ДО КОНЦА. `COMPOSITE_HEAD` говорит, с какого
   * куска начинается список компонентов; всё от него и дальше — ОДНО имя.
   * ⚠ Ограничение на число разрезов, а не отбрасывание кусков после: хвост
   * остаётся дословным текстом регламента вместе со своими разделителями.
   */
  const head = COMPOSITE_HEAD.get(indexNumber);
  const parts = [];
  for (const seg of splitTopLevel(cell, head ? head - 1 : Infinity)) {
    // ⭐ Сегмент, оказавшийся ЦЕЛИКОМ примечанием («titanium dioxide; [in powder
    // form…]»), своей формы не заводит: он относится ко ВСЕЙ записи.
    const whole = seg.startsWith('[') ? tailGroup(seg) : null;
    if (whole && !whole.before) {
      const kind = classifyAnnotation(indexNumber, whole.inner);
      if (kind !== 'name') { annotations.push({ kind, text: whole.inner }); continue; }
    }
    const name = peel(seg, indexNumber, annotations);
    if (name) parts.push(name);
  }
  return {
    kind: 'single', members: {},
    forms: parts.slice(0, 1), synonyms: parts, annotations, unbalanced,
  };
}
