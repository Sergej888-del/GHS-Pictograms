/**
 * Скобочный материал в именах веществ Annex VI Part 3.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠⚠ ПРАВИЛО ВЗЯТО ИЗ ПЕРВОИСТОЧНИКА, А НЕ ПРИДУМАНО.
 * Annex VI, Part 1, п. 1.1.1.4 «Chemical name», дословно:
 *
 *   «…the name of the substance to be used on the label shall be one of the
 *    designations given there. For certain substances, additional information
 *    has been added in square brackets in order to help identify the substance.
 *    This additional information need not be included on the label. Certain
 *    entries contain a reference to impurities; in these cases the name of the
 *    substance is followed by the text: “(containing ≥ xx % impurity)”. The
 *    reference in brackets is then to be considered as a part of the name, and
 *    must be included on the label.»
 *
 * То есть регламент сам делит скобочный материал надвое: «дополнительные
 * сведения» печатать НЕ ОБЯЗАНЫ, ссылку на примесь печатать ОБЯЗАНЫ.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * ⚠⚠ РАЗЛИЧАТЬ ПО ВИДУ СКОБКИ НЕЛЬЗЯ. Замер по 23 языковым версиям: у одной и
 * той же записи вид скобки между языками РАЗНЫЙ.
 *
 *   601-004-01-8
 *     en: butane (containing ≥ 0,1 % butadiene (203-450-8)); [1] …      круглые
 *     el: βουτάνιο [που περιέχει ≥ 0,1 % βουταδιένιο (203-450-8)]· [1] … квадратные
 *     fr: acide p-toluènesulfonique, contenant plus de 5 % de H₂SO₄     без скобок
 *
 * Правило «квадратные = условие» напечатало бы РАЗНЫЙ ПО СУЩЕСТВУ текст на
 * разных языках ОДНОЙ этикетки. Поэтому класс определяется ПО СУЩЕСТВУ и
 * закрепляется ЗА ИНДЕКСНЫМ НОМЕРОМ — один и тот же во всех 23 языках.
 *
 * ⚠⚠ И ГЛАВНОЕ: правило «скобки = условие» сломало бы больше, чем чинит.
 * Замер сегментов по 23 языкам:
 *
 *   138 481 (4 073 номера)  имя, скобок нет
 *    21 769 (2 134 номера)  имя, скобка — ЧАСТЬ ХИМИЧЕСКОЙ НОМЕНКЛАТУРЫ
 *    11 192 (  623 номера)  описание EINECS/UVCB (каменноугольные смолы)
 *       970 (  129 номеров) прочие примечания
 *       469 (   45 номеров) состав/примесь
 *       358 (   20 номеров) аббревиатура
 *
 * `[(p-tolyloxy)methyl]oxirane`, `[phosphinyldynetris(oxy)] tris[…]`,
 * `[μ-[carbonato(2-)-O:O']]dihydroxy trinickel` — это ИМЕНА, и их 2 134 записи
 * против 817 засорённых, то есть вдвое с лишним больше.
 *
 * ⭐ ОТСЮДА ФОРМА ПРАВИЛА: не эвристика по тексту, а ЯВНАЯ ТАБЛИЦА по индексному
 * номеру. Множество значений поля перечислимо целиком (683 номера, из них 636 —
 * одно семейство 648/649/650), а session 49 трижды поплатилась за починку «по
 * найденному примеру» вместо «по множеству возможных значений».
 * ⚠ Чего в таблице нет — остаётся ИМЕНЕМ и попадает в отчёт. Молчаливого
 * отбрасывания здесь быть не должно.
 *
 * ⚠⚠ ИМЯ НЕ ПЕРЕПИСЫВАЕТСЯ. Примечания складываются в отдельный список и
 * привязаны к ЗАПИСИ, а не к форме: примесь по п. 1.1.1.4 обязана попасть на
 * этикетку, какую бы из designations человек ни выбрал. Дописывать её к одной
 * форме и не дописывать к другой — значит сделать печать зависящей от выбора.
 */

