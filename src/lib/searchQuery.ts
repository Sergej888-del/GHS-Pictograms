/**
 * Единая чистка строки поиска вещества — №149, session 91.
 *
 * Зачем: лог «искал и не нашёл» (`tool_search_miss`, s88–s90) показал промахи на
 * вещества, которые В БАЗЕ ЕСТЬ:
 *   • «１０８－８８－３» — полноширинные цифры японской раскладки, ×5 за три недели —
 *     толуол 108-88-3 лежит в справочнике;
 *   • «CAS 111-90-0», «CAS 1317-36-8» — номер скопирован из паспорта безопасности
 *     вместе с подписью;
 *   • «98‑95‑3», «98–95–3» — неразрывный дефис и тире из PDF.
 * Шесть островов искали шестью способами: PStatementSelector снимал префикс «CAS»
 * с session 74, остальные пять — нет, и ни один не видел полноширинных цифр.
 * Здесь — один вход для всех шести и для `/api/classify/lookup`.
 *
 * ⚠⚠ Чистим ТОЛЬКО форму записи. Регистр и орфографию (sulph → sulf,
 * aluminium → aluminum) каждый остров приводит сам, потому что то же правило он
 * применяет к своему индексу Fuse; здесь их трогать нельзя — индекс этого не увидит.
 * Цифры не переставляем, номер не «исправляем», контрольную сумму не считаем:
 * задача — чтобы то, что человек вставил, совпало с тем, что лежит в базе.
 *
 * Сторож: `scripts/check-search.ts` (`npm run check:search`) — фикстуры из живого
 * лога промахов + прогон через Fuse по `dist/data/substances-index.json`.
 */

/** Все виды тире, которые люди и PDF подставляют вместо дефиса. NFKC их не трогает. */
const DASHES = /[‐-―−⁃﹘﹣]/g

/** Неразрывный и типографские пробелы → обычный. */
const SPACES = /[   -​  　]/g

/**
 * Подпись «CAS» перед номером: «CAS 108-88-3», «CAS No. 108-88-3», «CAS№ 108-88-3»,
 * «CAS#108-88-3», «CAS RN: 108-88-3», «CAS Nr. 108-88-3», «cas-108-88-3».
 * ⚠ `(?![a-z])` — а не `\b`: «castor oil» и «Caspofungin» трогать нельзя,
 * а «CAS108-88-3» (без пробела) — можно.
 * ⚠ NFKC превращает «№» в «No» — поэтому слово-подпись допускается и ВПРИТЫК к «CAS»
 * («CAS№ 98-95-3» → «CASNo 98-95-3»), а запрет на букву стоит уже ПОСЛЕ него.
 */
const CAS_PREFIX = /^cas[\s.:#-]*(?:no\.?|number|nr\.?|rn)?(?![a-z])[\s.:#-]*/i

/** Знак препинания, прилипший к концу («108-88-3.», «acetone,»). */
const TRAILING_PUNCT = /[.,;:]+$/

export function normalizeSearchQuery(raw: string | null | undefined): string {
  const s = (raw ?? '')
    // полноширинные цифры/латиница/знаки → ASCII: １０８ → 108, ＣＡＳ → CAS, － → -
    .normalize('NFKC')
    .replace(DASHES, '-')
    .replace(SPACES, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  return s.replace(CAS_PREFIX, '').replace(TRAILING_PUNCT, '').trim()
}

/**
 * Похоже ли введённое на номер CAS: 2–7 цифр, дефис, две цифры, дефис, контрольная.
 * Один регэксп на всех — чтобы остров с точным поиском по номеру и остров с Fuse
 * понимали под «номером» одно и то же.
 */
export const CAS_SHAPE = /^\d{2,7}-\d{2}-\d$/

/** Нормализованная строка — номер CAS? */
export function looksLikeCas(normalized: string): boolean {
  return CAS_SHAPE.test(normalized)
}
