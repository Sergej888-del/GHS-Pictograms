// ── Примитивы раскладки ─────────────────────────────────────────────────────

export type DrawText = {
  t: 'text';
  x: number; y: number; // мм, y — базовая линия
  s: string;
  size: number;         // мм, высота кегля
  bold?: boolean;
  italic?: boolean;
  mono?: boolean;
  color: string;
  anchor?: 'start' | 'middle';
};
export type DrawRect = {
  t: 'rect';
  x: number; y: number; w: number; h: number;
  stroke?: string; strokeW?: number; fill?: string; radius?: number; dash?: number;
};
export type DrawLine = {
  t: 'line';
  x1: number; y1: number; x2: number; y2: number;
  stroke: string; strokeW: number; dash?: number;
};
/** Пиктограмма: исходный SVG, который вставляется в превью и растеризуется в PDF. */
export type DrawSvg = { t: 'svg'; x: number; y: number; size: number; svg: string; code: string };
/** Растровый логотип пользователя (PNG/JPEG data URL). */
export type DrawImage = { t: 'image'; x: number; y: number; w: number; h: number; href: string };

export type DrawItem = DrawText | DrawRect | DrawLine | DrawSvg | DrawImage;

export type LabelLayout = {
  widthMm: number;
  heightMm: number;
  items: DrawItem[];
  fit: LabelFit;
  issues: ComplianceIssue[];
  pictogramMm: number;
};

export type LabelFit = {
  /** Всё содержимое поместилось при читаемом кегле. */
  fits: boolean;
  /** Минимальная высота при заказанной ширине, при которой всё влезает. */
  neededHeightMm: number;
  /** Размер пиктограммы, который получился. */
  pictogramMm: number;
  /** Требуемый регламентом минимум стороны пиктограммы; null — нормы нет. */
  requiredPictogramMm: number | null;
  /** Заказанный размер меньше предписанного таблицей; null — таблицы нет. */
  belowMinimum: boolean | null;
  minimumLabel: string | null;
  /** Кегль основного текста, мм. */
  bodyMm: number;
  /** Кегль, который движок выбрал бы сам. Равен `bodyMm`, если поправки нет. */
  autoBodyMm: number;
  /**
   * Ручная поправка кегля упёрлась в границу и дальше не пошла.
   *
   * ⚠⚠ Молча зажать значение нельзя: ползунок стоял бы на 60 %, а печаталось бы
   * 100 %, и человек считал бы, что настройка не работает. Интерфейс обязан
   * сказать, во что именно упёрлись.
   */
  bodyClampedTo: 'min' | 'max' | null;
  /**
   * ⭐ Самый крупный кегль, при котором содержимое ЕЩЁ влезает в заказанную
   * высоту. `null` — запаса нет, автоподбор уже упёрся в высоту.
   *
   * ⚠⚠ Без этого числа ползунок «увеличить» — ловушка. Автоподбор берёт
   * максимум, при котором влезает, значит крутить вверх почти всегда означает
   * «этикетка вырастет и перестанет соответствовать купленной заготовке».
   * Запас есть ровно в одном случае: когда автоподбор упёрся не в высоту, а в
   * СВОЙ потолок `maxBody` — то есть на крупной этикетке с коротким набором
   * фраз. Ради этого случая настройка и заводится, и интерфейс обязан показать,
   * где кончается «влезает» и начинается «этикетка растёт».
   */
  maxFittingBodyMm: number | null;
};

/** Замечание о соответствии: чего не хватает и по какой норме. */
export type ComplianceIssue = {
  level: 'error' | 'warning' | 'info';
  text: string;
  citation?: string;
};

// ── Вход ────────────────────────────────────────────────────────────────────

export type Statement = { code: string; text: string };

/**
 * Степень опасности, которую объявляет сигнальное слово.
 *
 * ⚠⚠ ЭТО ОТДЕЛЬНОЕ ПОЛЕ, А НЕ РАЗБОР НАПЕЧАТАННОГО СЛОВА, И ВОТ ПОЧЕМУ.
 * Пока сигнальное слово было только английским, `/danger/i` по строке работал.
 * С выбором языка на этикетке стоит «Gefahr», «Achtung», «Gevaar», «Vaara» —
 * и разбор строки отдаёт для немецкого «Gefahr» ЯНТАРНЫЙ, то есть этикетка
 * уровня Danger печатается цветом предупреждения. Причём молча: слово на месте,
 * цвет «какой-то есть», и заметить это может только человек, знающий язык.
 *
 * Степень приходит из классификации. Слово — только для печати.
 */
export type SignalLevel = 'danger' | 'warning';

/**
 * Второй язык этикетки — для Канады обязателен, в остальных местах опция.
 *
 * ⚠ Сигнального слова здесь нет как отдельной степени: степень у этикетки ОДНА
 * (`LabelInput.signalLevel`), а `signalWord` — то же слово на другом языке.
 * Двух разных степеней на одной этикетке быть не может.
 */
export type SecondLanguageBlock = {
  langTag: string;      // «FR», «ES»
  signalWord: string | null;
  /**
   * Имя вещества на этом языке. Обязательный элемент: CLP ст. 17(1)(c) плюс
   * ст. 17(2) — «одни и те же сведения во всех использованных языках».
   * `undefined` — перевода имени у нас нет; тогда второе имя не печатается,
   * выдумывать его нельзя.
   */
  productName?: string;
  hStatements: Statement[];
  pStatements: Statement[];
  combinedPText?: string;
  /**
   * ⚠⚠ РАВНОПРАВНЫЙ, А НЕ ПОДЧИНЁННЫЙ БЛОК.
   *
   * По умолчанию второй язык печатается курсивом и приглушённым серым — так
   * читатель видит пару «фраза и её перевод», и это верно там, где второй язык
   * добавлен по желанию поставщика.
   *
   * Но в Канаде (HPR s. 6.2) английский и французский обязательны ОБА, и в
   * Бельгии этикетка обязана быть на официальном языке рынка (CLP Art. 17(2)),
   * а их там три. В таком месте серый курсив — не оформление, а утверждение:
   * «этот текст второстепенный». Юридически он не второстепенный, и подача
   * должна это отражать: тот же кегль, тот же цвет, никакого курсива.
   */
  equal?: boolean;
};

export type LabelInput = {
  productName: string;
  casNumber?: string;
  ecNumber?: string | null;
  nominalQty?: string;
  batchNumber?: string;
  ufiCode?: string;
  signalWord: string | null;
  /**
   * Степень опасности. ⚠ Необязательное поле только ради обратной совместимости:
   * когда его нет, степень выводится из английского слова (см. `levelOf`).
   * У любого нового вызывающего оно должно быть.
   */
  signalLevel?: SignalLevel | null;
  pictograms: { code: string; svg: string }[];
  hStatements: Statement[];
  pStatements: Statement[];
  pFormat: 'codes' | 'combined';
  combinedPText?: string;
  hiddenPCount?: number;
  supplier: { name?: string; address?: string; phone?: string };
  logo?: { dataUrl: string; aspect: number };
  second?: SecondLanguageBlock;
  /** Служебные строки внизу: отсылка к внешней упаковке, наличие SDS и т. п. */
  notes?: string[];
};

export type LabelOptions = {
  jurisdiction: JurisdictionKey;
  purpose: LabelPurpose;
  widthMm: number;
  heightMm: number;
  /** Объём тары в литрах — им выбирается ярус минимальных размеров CLP. */
  containerLitres?: number;
  /** Объём тары в миллилитрах — им проверяются послабления для малой тары. */
  containerMl?: number;
  /**
   * ⭐ РУЧНАЯ ПОПРАВКА КЕГЛЯ — доля от подобранного автоматически. `1` или
   * `undefined` — как было, движок выбирает сам.
   *
   * ⚠⚠ ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО, ЕСЛИ КЕГЛЬ И ТАК ПОДБИРАЕТСЯ. Автоподбор берёт
   * САМЫЙ КРУПНЫЙ кегль, при котором содержимое влезает по высоте, а дальше
   * упирается в потолок `maxBody`. На крупной этикетке с коротким набором фраз
   * потолок срабатывает раньше высоты — и остаётся воздух, который человек
   * хочет занять текстом. Автоподбор этого решить не может: «заполнить или
   * оставить поля» — вопрос вкуса и печати, а не раскладки.
   *
   * ⛔ НИЖНЯЯ ГРАНИЦА ЖЁСТКАЯ И НЕ ОБХОДИТСЯ. Кегль зажимается в
   * `[MIN_BODY_MM, BODY_MM_CEILING]` ПОСЛЕ умножения. Ползунок не может
   * напечатать нечитаемую этикетку, даже если попросить.
   *
   * ⚠ Регламент числового минимума кегля НЕ задаёт — проверено по
   * первоисточнику. CLP ст. 31(3): «of such size and spacing as to be easily
   * read», требование качественное; Table 1.3 задаёт минимумы только для
   * этикетки и пиктограммы. Значит `MIN_BODY_MM` — НАШ порог, а не норма, и
   * называть его в интерфейсе надо своим именем.
   */
  bodyScale?: number;
};

// ── Метрика текста ────────────────────────────────────────────────────────
//
// ⭐⭐ ЗДЕСЬ СЧИТАЮТСЯ НАСТОЯЩИЕ ШИРИНЫ ЗНАКОВ, А НЕ СРЕДНЯЯ ПО ПАЛАТЕ.
//
// ⚠⚠ БЫЛО: одна константа `CW_REGULAR = 0.52` — «средняя ширина знака в долях
// кегля» — на все 24 языка. Переносы считались по ЧИСЛУ знаков:
// `charsPerLine = floor(widthMm / (sizeMm × 0.52))`. Это не придирка к точности,
// а источник двух противоположных дефектов сразу.
//
// **Замер (session 64), метрики Arial, все 24 языка Annex IV.** Ширина каждого
// из 306 знаков, встречающихся в `statement_translations`, взята прямо из
// шрифта (`fontTools`, Liberation Sans — метрически совместим с Arial). Цифры
// сошлись с независимым замером session 63 в Chromium через
// `canvas.measureText` до четвёртого знака: BG 0,5160 · EL 0,4904 · DE 0,4817 ·
// EN 0,4503 · MT 0,4418. Два разных метода дали одно.
//
// ⛔ **И этот замер отменил напрашивавшуюся правку «сделать CW функцией
// языка».** Средняя описывает ЯЗЫК, а переполняется КОНКРЕТНАЯ фраза. Внутри
// одного языка разброс больше, чем между языками:
//
//   польский   средняя 0,4883 → худшая переносимая фраза 0,6309
//   болгарский средняя 0,5160 → худшая 0,5787, и фраз шире 0,52 у него 23 штуки
//   английский средняя 0,4503 → худшая 0,5294
//
// То есть `CW_EN = 0.4503` сломал бы и английский: его же собственная фраза
// требует на 17,6 % больше. И сегодняшняя 0,52 мала — фразы шире неё есть в
// 23 языках из 24.
//
// ⭐ Отсюда решение: не подбирать мерку, а **складывать настоящие ширины**.
// Тогда ни общей константы, ни таблицы по языкам не нужно вовсе — кириллица,
// греческий и многоточие (ровно 1,0 кегля, вдвое шире прежней мерки) считаются
// точно. Заодно возвращается место там, где 0,52 была завышена: у мальтийского
// это 17,7 % строки.
//
// ⚠ Мерка берётся по **Arial**, а не по Noto Sans, которой набирается PDF.
// Noto на 6–9 % ýже, переносы считаются один раз на оба вывода, значит
// связывающий случай — SVG. Возьми Noto — SVG будет переливаться.
//
// ⚠ Таблицы сгенерированы, а не набраны руками. Повторить:
// `fontTools.ttLib.TTFont(LiberationSans-Regular.ttf)`, `hmtx[glyph][0] /
// head.unitsPerEm`, знаки сгруппированы по одинаковой ширине.
// Невидимые знаки (U+00A0, U+00AD) записаны escape'ами СОЗНАТЕЛЬНО: в
// исходнике они неотличимы от обычного пробела и дефиса.

